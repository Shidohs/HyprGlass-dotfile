#!/usr/bin/env bash
# HyprGlass - Theme Unifier & Hot-Reload Engine
# Synchronizes GTK, Qt, Kitty, Alacritty, Waybar, Rofi, and SwayNC themes seamlessly.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
LIB_DIR="$SCRIPT_DIR/../lib"

if [[ -f "$LIB_DIR/logging.sh" ]]; then
    # shellcheck disable=SC1091
    source "$LIB_DIR/logging.sh"
else
    log_info() { echo "[INFO] $1"; }
    log_warn() { echo "[WARN] $1"; }
    log_error() { echo "[ERROR] $1"; }
fi

# shellcheck disable=SC1091
source "$SCRIPT_DIR/theme-lib.sh"

KVANTUM_CONFIG_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/Kvantum"
KVANTUM_CONF_FILE="$KVANTUM_CONFIG_DIR/kvantum.kvconfig"
GTK3_CONFIG="${XDG_CONFIG_HOME:-$HOME/.config}/gtk-3.0"
GTK4_CONFIG="${XDG_CONFIG_HOME:-$HOME/.config}/gtk-4.0"
XSETTINGS_CONFIG="$HOME/.xsettingsd"
XSETTINGS_CONFIG_ALT="${XDG_CONFIG_HOME:-$HOME/.config}/xsettingsd/xsettingsd.conf"
QT5CT_CONFIG="${XDG_CONFIG_HOME:-$HOME/.config}/qt5ct"
QT6CT_CONFIG="${XDG_CONFIG_HOME:-$HOME/.config}/qt6ct"
GTKRC2="$HOME/.gtkrc-2.0"
ROFI_CONFIG_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/rofi"
QT_SYSTEM_STYLE="gtk2"
QT_COLOR_SCHEME_PATH="${XDG_DATA_HOME:-$HOME/.local/share}/color-schemes/Lyne.colors"

show_help() {
    cat <<'EOF'
Usage: theme-unifier.sh [apply|reload|status|reset|help]
EOF
}

detect_qt_platformtheme() {
    local -a qt6_plugins=(
        "/usr/lib/qt6/plugins/platformthemes/libqt6ct.so"
        "/usr/lib/qt6/plugins/platformthemes/qt6ct.so"
        "/usr/lib/qt6/plugins/platformthemes/libqt6ct.so.1"
    )
    local -a qt5_plugins=(
        "/usr/lib/qt/plugins/platformthemes/libqt5ct.so"
        "/usr/lib/qt/plugins/platformthemes/qt5ct.so"
        "/usr/lib/qt5/plugins/platformthemes/libqt5ct.so"
        "/usr/lib/qt5/plugins/platformthemes/qt5ct.so"
        "/usr/lib/x86_64-linux-gnu/qt5/plugins/platformthemes/libqt5ct.so"
    )
    local -a gtk3_plugins=(
        "/usr/lib/qt6/plugins/platformthemes/libqgtk3.so"
        "/usr/lib/qt6/plugins/platformthemes/qgtk3.so"
        "/usr/lib/qt/plugins/platformthemes/libqgtk3.so"
        "/usr/lib/qt/plugins/platformthemes/qgtk3.so"
        "/usr/lib/qt5/plugins/platformthemes/libqgtk3.so"
        "/usr/lib/qt5/plugins/platformthemes/qgtk3.so"
        "/usr/lib/x86_64-linux-gnu/qt5/plugins/platformthemes/libqgtk3.so"
    )
    local plugin

    for plugin in "${qt6_plugins[@]}"; do
        [[ -f "$plugin" ]] && { echo "qt6ct"; return 0; }
    done
    for plugin in "${qt5_plugins[@]}"; do
        [[ -f "$plugin" ]] && { echo "qt5ct"; return 0; }
    done
    for plugin in "${gtk3_plugins[@]}"; do
        [[ -f "$plugin" ]] && { echo "gtk3"; return 0; }
    done
}

get_configured_qt_style() {
    local config style
    for config in "$QT5CT_CONFIG/qt5ct.conf" "$QT6CT_CONFIG/qt6ct.conf"; do
        [[ -f "$config" ]] || continue
        style="$(sed -n 's/^style=//p' "$config" | head -n 1)"
        if [[ "$style" =~ ^[A-Za-z0-9._-]+$ ]]; then
            printf '%s\n' "$style"
            return 0
        fi
    done
}

sync_rofi_icon_theme() {
    [[ -d "$ROFI_CONFIG_DIR" ]] || return 0

    while IFS= read -r -d '' file; do
        sed -i -E \
            "s/(icon-theme[[:space:]]*:[[:space:]]*)\"[^\"]*\"/\1\"$ICON_THEME\"/g" \
            "$file"
    done < <(find "$ROFI_CONFIG_DIR" -type f -name '*.rasi' -print0)
}

write_hypr_env_conf() {
    local platformtheme=""

    mkdir -p "$(dirname "$HYPR_THEME_ENV_CONF")"
    platformtheme="$(detect_qt_platformtheme || true)"

    {
        echo "# Generated by ~/.config/hypr/scripts/system/theme-unifier.sh"
        echo "env = XCURSOR_THEME,$CURSOR_THEME"
        echo "env = QT_CURSOR_THEME,$CURSOR_THEME"
        echo "env = HYPRCURSOR_THEME,$CURSOR_THEME"
        echo "envd = XCURSOR_SIZE,$CURSOR_SIZE"
        echo "envd = QT_CURSOR_SIZE,$CURSOR_SIZE"
        echo "envd = HYPRCURSOR_SIZE,$CURSOR_SIZE"
        if [[ -n "$platformtheme" ]]; then
            echo "env = QT_QPA_PLATFORMTHEME,$platformtheme"
        fi
    } > "$HYPR_THEME_ENV_CONF"
}

create_gtk_configs() {
    mkdir -p "$GTK3_CONFIG" "$GTK4_CONFIG"

    cat > "$GTK3_CONFIG/settings.ini" <<EOF
[Settings]
gtk-theme-name=$GTK_THEME
gtk-icon-theme-name=$ICON_THEME
gtk-cursor-theme-name=$CURSOR_THEME
gtk-cursor-theme-size=$CURSOR_SIZE
gtk-font-name=Cantarell 11
gtk-application-prefer-dark-theme=true
gtk-decoration-layout=:minimize,maximize,close
gtk-enable-animations=true
gtk-primary-button-warps-slider=false
EOF

    cat > "$GTK4_CONFIG/settings.ini" <<EOF
[Settings]
gtk-theme-name=$GTK_THEME
gtk-icon-theme-name=$ICON_THEME
gtk-cursor-theme-name=$CURSOR_THEME
gtk-cursor-theme-size=$CURSOR_SIZE
gtk-font-name=Cantarell 11
gtk-application-prefer-dark-theme=true
gtk-decoration-layout=:minimize,maximize,close
gtk-enable-animations=true
gtk-primary-button-warps-slider=false
EOF

    cat > "$GTKRC2" <<EOF
gtk-theme-name="$GTK_THEME"
gtk-icon-theme-name="$ICON_THEME"
gtk-cursor-theme-name="$CURSOR_THEME"
gtk-cursor-theme-size=$CURSOR_SIZE
gtk-font-name="Cantarell 11"
EOF
}

create_xsettings_config() {
    mkdir -p "$(dirname "$XSETTINGS_CONFIG")" "$(dirname "$XSETTINGS_CONFIG_ALT")"

    local content
    content=$(cat <<EOF
# Generated by theme-unifier.sh. Do not edit manually.
Net/ThemeName "$GTK_THEME"
Net/IconThemeName "$ICON_THEME"
Gtk/CursorThemeName "$CURSOR_THEME"
Gtk/CursorThemeSize $CURSOR_SIZE
Gtk/ApplicationPreferDarkTheme 1
Net/EnableEventSounds 0
EnableInputFeedbackSounds 0
EOF
)

    printf '%s\n' "$content" > "$XSETTINGS_CONFIG"
    printf '%s\n' "$content" > "$XSETTINGS_CONFIG_ALT"
}

clear_gtk_css_overrides() {
    local path
    for path in \
        "$GTK3_CONFIG/gtk.css" \
        "$GTK3_CONFIG/gtk-dark.css" \
        "$GTK3_CONFIG/assets" \
        "$GTK4_CONFIG/gtk.css" \
        "$GTK4_CONFIG/gtk-dark.css" \
        "$GTK4_CONFIG/assets"; do
        if [[ -L "$path" ]]; then
            rm -f "$path"
        fi
    done
}

clear_generated_palette_overrides() {
    # The system appearance path owns the generated palette below. Remove the
    # old KDE merge so a previous preset cannot override the selected GTK
    # theme before the new palette is loaded.
    local kdeglobals="${XDG_CONFIG_HOME:-$HOME/.config}/kdeglobals"
    [[ -f "$kdeglobals" ]] || return 0
    sed -i '/^ColorScheme=Lyne$/d; /^Name=Lyne$/d' "$kdeglobals"
}

hex_to_rgb() {
    local hex="${1#\#}"
    [[ "$hex" =~ ^[0-9A-Fa-f]{6}$ ]] || {
        printf '0,0,0\n'
        return 0
    }
    printf '%d,%d,%d\n' \
        "$((16#${hex:0:2}))" \
        "$((16#${hex:2:2}))" \
        "$((16#${hex:4:2}))"
}

write_qt_palette_from_gtk() {
    local gtk_css theme_fg theme_bg theme_base selected_bg selected_fg
    local text_color bg_color surface_color border_color

    gtk_css="$HOME/.themes/$GTK_THEME/gtk-3.0/gtk.css"
    [[ -f "$gtk_css" ]] || gtk_css="/usr/share/themes/$GTK_THEME/gtk-3.0/gtk.css"
    [[ -f "$gtk_css" ]] || return 0

    gtk_color() {
        sed -n "s/^[[:space:]]*@define-color[[:space:]]\+$1[[:space:]]\+\(#[0-9A-Fa-f]\{6,8\}\).*/\1/p" "$gtk_css" | head -n 1
    }

    theme_fg="$(gtk_color theme_fg_color)"
    theme_bg="$(gtk_color theme_bg_color)"
    theme_base="$(gtk_color theme_base_color)"
    selected_bg="$(gtk_color theme_selected_bg_color)"
    selected_fg="$(gtk_color theme_selected_fg_color)"
    text_color="$(hex_to_rgb "${theme_fg:-#d8dee9}")"
    bg_color="$(hex_to_rgb "${theme_bg:-#2e3440}")"
    theme_base="${theme_base:-#3b4252}"
    surface_color="$(hex_to_rgb "$theme_base")"
    border_color="$(gtk_color borders)"
    border_color="$(hex_to_rgb "${border_color:-#232831}")"
    selected_bg="$(hex_to_rgb "${selected_bg:-#8fbcbb}")"
    selected_fg="$(hex_to_rgb "${selected_fg:-#d8dee9}")"
    theme_base="$(hex_to_rgb "$theme_base")"

    mkdir -p "$(dirname "$QT_COLOR_SCHEME_PATH")"
    cat > "$QT_COLOR_SCHEME_PATH" <<EOF
[ColorEffects:Disabled]
Color=128,128,128
ColorAmount=0
ColorEffect=0
ContrastAmount=0.65
ContrastEffect=1
IntensityAmount=0.1
IntensityEffect=2

[Colors:Button]
BackgroundAlternate=$surface_color
BackgroundNormal=$surface_color
DecorationFocus=$selected_bg
DecorationHover=$selected_bg
ForegroundActive=$selected_bg
ForegroundInactive=$text_color
ForegroundLink=$selected_bg
ForegroundNormal=$text_color
ForegroundPositive=$selected_bg
ForegroundVisited=$text_color

[Colors:View]
BackgroundAlternate=$surface_color
BackgroundNormal=$theme_base
DecorationFocus=$selected_bg
DecorationHover=$selected_bg
ForegroundActive=$selected_bg
ForegroundInactive=$text_color
ForegroundLink=$selected_bg
ForegroundNormal=$text_color
ForegroundPositive=$selected_bg
ForegroundVisited=$text_color

[Colors:Window]
BackgroundAlternate=$surface_color
BackgroundNormal=$bg_color
DecorationFocus=$selected_bg
DecorationHover=$selected_bg
ForegroundActive=$selected_bg
ForegroundInactive=$text_color
ForegroundLink=$selected_bg
ForegroundNormal=$text_color
ForegroundPositive=$selected_bg
ForegroundVisited=$text_color

[Colors:Selection]
BackgroundAlternate=$selected_bg
BackgroundNormal=$selected_bg
DecorationFocus=$selected_bg
DecorationHover=$selected_bg
ForegroundActive=$selected_bg
ForegroundInactive=$selected_fg
ForegroundLink=$selected_fg
ForegroundNormal=$selected_fg
ForegroundPositive=$selected_fg
ForegroundVisited=$selected_fg

[WM]
activeBackground=$bg_color
activeBlend=$surface_color
activeForeground=$text_color
inactiveBackground=$bg_color
inactiveBlend=$bg_color
inactiveForeground=$text_color

[General]
ColorScheme=SystemAppearance
Name=SystemAppearance
EOF
}

create_qt_configs() {
    write_qt_palette_from_gtk
    mkdir -p "$QT5CT_CONFIG" "$QT6CT_CONFIG"

    cat > "$QT5CT_CONFIG/qt5ct.conf" <<EOF
[Appearance]
color_scheme_path=$QT_COLOR_SCHEME_PATH
custom_palette=true
icon_theme=$ICON_THEME
standard_dialogs=gtk3
style=$QT_SYSTEM_STYLE

[Fonts]
fixed=Noto Sans Mono,10,-1,5,50,0,0,0,0,0
general=Noto Sans,10,-1,5,50,0,0,0,0,0
EOF

    cat > "$QT6CT_CONFIG/qt6ct.conf" <<EOF
[Appearance]
color_scheme_path=$QT_COLOR_SCHEME_PATH
custom_palette=true
icon_theme=$ICON_THEME
standard_dialogs=gtk3
style=$QT_SYSTEM_STYLE

[Fonts]
fixed=Noto Sans Mono,10,-1,5,50,0,0,0,0,0
general=Noto Sans,10,-1,5,50,0,0,0,0,0
EOF
}

apply_gsettings() {
    command -v gsettings >/dev/null 2>&1 || return 0

    gsettings set org.gnome.desktop.interface gtk-theme "$GTK_THEME" || true
    gsettings set org.gnome.desktop.interface icon-theme "$ICON_THEME" || true
    gsettings set org.gnome.desktop.interface cursor-theme "$CURSOR_THEME" || true
    gsettings set org.gnome.desktop.interface cursor-size "$CURSOR_SIZE" || true
    gsettings set org.gnome.desktop.interface font-name "Cantarell 11" || true
    gsettings set org.gnome.desktop.interface color-scheme 'prefer-dark' || true
}

apply_runtime_hypr_env() {
    command -v hyprctl >/dev/null 2>&1 || return 0
    [[ -n "${HYPRLAND_INSTANCE_SIGNATURE:-}" ]] || return 0

    hyprctl keyword env "XCURSOR_THEME,$CURSOR_THEME" >/dev/null 2>&1 || true
    hyprctl keyword env "QT_CURSOR_THEME,$CURSOR_THEME" >/dev/null 2>&1 || true
    hyprctl keyword env "HYPRCURSOR_THEME,$CURSOR_THEME" >/dev/null 2>&1 || true
    hyprctl keyword env "XCURSOR_SIZE,$CURSOR_SIZE" >/dev/null 2>&1 || true
    hyprctl keyword env "QT_CURSOR_SIZE,$CURSOR_SIZE" >/dev/null 2>&1 || true
    hyprctl keyword env "HYPRCURSOR_SIZE,$CURSOR_SIZE" >/dev/null 2>&1 || true
}

reload_theme_components() {
    log_info "Synchronizing theme hot-reload across active desktop components..."

    # 1. Kitty: Send SIGUSR1 signal for instant hot reload
    if pgrep -x kitty >/dev/null 2>&1; then
        pkill -SIGUSR1 -x kitty 2>/dev/null || true
        log_info "  ✓ Kitty reloaded"
    fi

    # 2. Alacritty: Touch alacritty config to trigger live-reload watcher
    local alacritty_conf="${XDG_CONFIG_HOME:-$HOME/.config}/alacritty/alacritty.toml"
    if [[ -f "$alacritty_conf" ]]; then
        touch "$alacritty_conf" 2>/dev/null || true
        log_info "  ✓ Alacritty config touched"
    fi

    # 3. Waybar: Send SIGUSR2 for style/CSS reload
    if pgrep -x waybar >/dev/null 2>&1; then
        pkill -SIGUSR2 -x waybar 2>/dev/null || true
        log_info "  ✓ Waybar reloaded"
    fi

    # 4. SwayNC: Trigger client reload for notifications CSS/colors
    if command -v swaync-client >/dev/null 2>&1 && pgrep -x swaync >/dev/null 2>&1; then
        swaync-client -R -rs >/dev/null 2>&1 || true
        log_info "  ✓ SwayNC reloaded"
    fi

    # 5. XSettingsDaemon: Reload GTK settings daemon
    if pgrep -x xsettingsd >/dev/null 2>&1; then
        pkill -HUP -x xsettingsd 2>/dev/null || true
        log_info "  ✓ xsettingsd reloaded"
    fi
}

apply_theme() {
    load_theme_state
    clear_gtk_css_overrides
    clear_generated_palette_overrides
    create_gtk_configs
    create_xsettings_config
    create_qt_configs
    sync_rofi_icon_theme
    apply_gsettings
    write_hypr_env_conf
    apply_runtime_hypr_env
    reload_theme_components
}

show_status() {
    local platformtheme=""
    local qt_style=""

    load_theme_state
    platformtheme="$(detect_qt_platformtheme || true)"
    qt_style="$(get_configured_qt_style || true)"

    cat <<EOF
Theme state file: $THEME_STATE_FILE
Hypr env file: $HYPR_THEME_ENV_CONF
GTK_THEME=$GTK_THEME
ICON_THEME=$ICON_THEME
CURSOR_THEME=$CURSOR_THEME
CURSOR_SIZE=$CURSOR_SIZE
QT_QPA_PLATFORMTHEME=${platformtheme:-unset}
QT_STYLE=${qt_style:-unset}
EOF
}

reset_theme() {
    save_theme_state \
        "$THEME_DEFAULT_GTK" \
        "$THEME_DEFAULT_ICONS" \
        "$THEME_DEFAULT_CURSOR" \
        "$THEME_DEFAULT_CURSOR_SIZE"
    apply_theme
}

case "${1:-apply}" in
    apply)
        apply_theme
        ;;
    reload)
        reload_theme_components
        ;;
    status)
        show_status
        ;;
    reset)
        reset_theme
        ;;
    help|--help|-h)
        show_help
        ;;
    *)
        show_help
        exit 1
        ;;
esac
